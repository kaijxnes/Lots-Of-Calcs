#!/usr/bin/env node
/* Splits sitemap.xml into one sitemap per page family under /sitemaps/,
   plus /sitemap-index.xml listing them, so Search Console reports indexing
   for each family separately (submit sitemap-index.xml there once).

       node tools/build-sitemap-index.js

   sitemap.xml stays the single source: every generator writes its own
   marked block into it, and this runs after them all (last in the monthly
   rebuild). Entries outside any block — the homepage and calculators —
   go into /sitemaps/calculators.xml. */
const fs = require("fs");
const path = require("path");
const site = require("./lib/site.js");

const ROOT = site.ROOT, SITE = site.SITE;
const xml = fs.readFileSync(path.join(ROOT, "sitemap.xml"), "utf8");
const HEAD = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n';
const groups = {};
let rest = xml;
const re = /\n? *<!-- ([^:]+): generated by [^>]*-->\n([\s\S]*?) *<!-- end \1 -->/g;
let m;
while ((m = re.exec(xml))) {
  const slug = m[1].trim().toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  groups[slug] = (groups[slug] || "") + m[2];
  rest = rest.replace(m[0], "");
}
groups.calculators = (rest.match(/ *<url>[\s\S]*?<\/url>\n/g) || []).join("");
const count = (s) => (s.match(/<loc>/g) || []).length;
const total = Object.values(groups).reduce((a, s) => a + count(s), 0);
if (total !== count(xml)) throw new Error(`split lost URLs: ${total} of ${count(xml)}`);

const dir = path.join(ROOT, "sitemaps");
fs.rmSync(dir, { recursive: true, force: true });
fs.mkdirSync(dir);
const index = Object.keys(groups).sort().map((slug) => {
  const body = groups[slug];
  fs.writeFileSync(path.join(dir, slug + ".xml"), HEAD + body + "</urlset>\n");
  const last = (body.match(/<lastmod>([^<]+)<\/lastmod>/g) || []).map((x) => x.slice(9, 19)).sort().pop();
  return `  <sitemap>\n    <loc>${SITE}/sitemaps/${slug}.xml</loc>${last ? `\n    <lastmod>${last}</lastmod>` : ""}\n  </sitemap>\n`;
});
fs.writeFileSync(path.join(ROOT, "sitemap-index.xml"), '<?xml version="1.0" encoding="UTF-8"?>\n<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + index.join("") + "</sitemapindex>\n");
console.log(`sitemap index: ${index.length} sitemaps, ${total} URLs`);
