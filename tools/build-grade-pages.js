#!/usr/bin/env node
/* "18 out of 25 as a percentage" — a page per test score:

       /grade/18-out-of-25/     72%, a C on the common US scale

       node tools/build-grade-pages.js

   Percentage = score ÷ total × 100, shown to one decimal place where it
   isn't whole. Letter grades use the common US 10-point scale (A 90+, B
   80+, C 70+, D 60+, F below), which the page says varies by school. */
const fs = require("fs");
const path = require("path");
const site = require("./lib/site.js");
const { SITE } = site;

const BASE = "/grade/";
const TOTALS = [10, 12, 15, 20, 25, 30, 40, 50, 60, 80];

const slug = (s, t) => `${s}-out-of-${t}`;
const pct = (s, t) => s / t * 100;
const show = (v) => (Math.round(v * 10) / 10).toLocaleString("en-US", { maximumFractionDigits: 1 }) + "%";
const exact = (v) => Math.abs(v * 10 - Math.round(v * 10)) < 1e-9;
function letter(p) {
  /* compare on the rounded-to-1dp figure the page shows */
  const r = Math.round(p * 10) / 10;
  return r >= 90 ? "A" : r >= 80 ? "B" : r >= 70 ? "C" : r >= 60 ? "D" : "F";
}

function page(s, t) {
  const p = pct(s, t), L = letter(p), url = SITE + `${BASE}${slug(s, t)}/`, wrong = t - s;
  const approx = exact(p) ? "" : " (rounded)";
  const title = site.fitTitle(`${s} Out of ${t} as a Percentage = ${show(p)} (Grade ${L})`, `${s}/${t} as a Percentage = ${show(p)}`);
  const desc = `${s} out of ${t} is ${show(p)}${approx}: ${s} ÷ ${t} × 100. That's a${L === "A" || L === "F" ? "n" : ""} ${L} on the common US grading scale, with ${wrong} wrong. Every score out of ${t} in a table.`;
  const q = [
    [`What is ${s} out of ${t} as a percentage?`, `${show(p)}${approx}. Divide ${s} by ${t} to get ${(Math.round(s / t * 10000) / 10000)} and multiply by 100.`],
    [`What grade is ${s} out of ${t}?`, `On the common US 10-point scale, ${show(p)} is a${L === "A" || L === "F" ? "n" : ""} ${L}. Schools and countries use different boundaries, so check your own; the grade calculator lets you set them.`],
    [`How many can I get wrong out of ${t} and still get 90%?`, `${Math.floor(t * 0.1 + 1e-9)} — you need at least ${Math.ceil(t * 0.9 - 1e-9)} right.`]
  ];
  const ld = [site.webPage(title, desc, url), site.breadcrumb([["Home", SITE + "/"], ["Grade Calculator", SITE + BASE], [`${s} out of ${t}`, url]]), site.faqLd(q)];
  const rows = [];
  for (let k = t; k >= 0; k--) rows.push([k === s ? `<strong>${k} out of ${t}</strong>` : (k > 0 ? `<a href="${BASE}${slug(k, t)}/">${k} out of ${t}</a>` : `0 out of ${t}`), show(pct(k, t)), letter(pct(k, t))]);
  const others = TOTALS.filter((T) => T !== t && Number.isInteger(s * T / t)).map((T) => `<a href="${BASE}${slug(s * T / t, T)}/">${s * T / t} out of ${T}</a>`);
  return site.head({ title, desc, url, ld }) + `    <header class="site-header">
      <a class="back-link" href="${BASE}">← Grade calculator</a>
      <h1 class="page-title">${s} out of ${t} as a percentage</h1>
      <p class="page-subtitle">${s} out of ${t} is <strong>${show(p)}</strong>${approx} — a${L === "A" || L === "F" ? "n" : ""} <strong>${L}</strong> on the common US scale.</p>
    </header>

    <main class="tool">
      <div class="result-box">
        <div class="result-grid">
          <div class="result-row highlight"><span class="r-label">Percentage</span><span class="r-value">${show(p)}</span></div>
          <div class="result-row"><span class="r-label">Letter grade (US 10-point scale)</span><span class="r-value">${L}</span></div>
          <div class="result-row"><span class="r-label">Right / wrong</span><span class="r-value">${s} / ${wrong}</span></div>
        </div>
      </div>
      <p class="about-text" style="margin-top:16px;"><strong>Working:</strong> ${s} ÷ ${t} = ${(Math.round(s / t * 10000) / 10000)}, and × 100 = ${show(p)}.${others.length ? ` The same percentage as ${others.join(", ")}.` : ""}</p>
      <p class="tool-hint">Grade boundaries vary: many UK and international tests use different ones. Set your own in the <a href="${BASE}">grade calculator</a>, which also does weighted grades.</p>
    </main>

    <main class="tool">
      <h2 class="tool-section-title">Every score out of ${t}</h2>
${site.table(["Score", "Percentage", "Grade"], rows, 300)}    </main>

    <main class="tool">
      <h2 class="tool-section-title">Frequently asked questions</h2>
${site.faqHtml(q)}    </main>

${site.FOOTER}
  </div>
</body>
</html>
`;
}

function hubBlock() {
  const file = path.join(site.ROOT, "grade/index.html");
  const START = "    <!-- grade pages: generated by tools/build-grade-pages.js -->\n", END = "    <!-- end grade pages -->\n";
  let s = fs.readFileSync(file, "utf8");
  if (s.includes(START)) s = s.slice(0, s.indexOf(START)) + s.slice(s.indexOf(END) + END.length).replace(/^\n+/, "");
  const html = `    <main class="tool">
      <h2 class="tool-section-title">Test scores as percentages</h2>
${TOTALS.map((t) => { const l = []; for (let k = t; k >= 1; k--) l.push(`<a href="${BASE}${slug(k, t)}/">${k}</a>`); return `      <p class="salary-links"><strong>Out of ${t}:</strong> ${l.join(" ")}</p>`; }).join("\n")}
    </main>

`;
  const at = s.indexOf("    <!-- related calculators: generated by tools/related.js -->");
  if (at < 0) throw new Error("grade: related marker not found");
  s = s.slice(0, at).replace(/\n{3,}$/, "\n\n") + START + html + END + "\n" + s.slice(at);
  fs.writeFileSync(file, s);
}

/* Hand checks: 18/25 = 72% C; 17/20 = 85% B; 2/3 of 30 = 66.7% D; 27/30 = 90% A */
if (show(pct(18, 25)) !== "72%" || letter(pct(17, 20)) !== "B" || show(pct(20, 30)) !== "66.7%" || letter(pct(27, 30)) !== "A") throw new Error("grade check");

const urls = [];
TOTALS.forEach((t) => { for (let s = 1; s <= t; s++) { site.write(`grade/${slug(s, t)}`, page(s, t)); urls.push([`${BASE}${slug(s, t)}/`, "0.4"]); } });
hubBlock();
site.prune("grade", /^\d+-out-of-\d+$/);
site.sitemapBlock("grade pages", "tools/build-grade-pages.js", urls);
console.log(`built ${urls.length} grade pages`);
