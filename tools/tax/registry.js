/* Reading the tax registry from disk, for the node tools. The browser goes
   through TaxEngine.load() and data/tax/index.json instead. */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..", "..");
const DATA = path.join(ROOT, "data", "tax");

function slugYear(label) {
  return String(label).replace(/\//g, "-");
}

/* Every jurisdiction document, keyed by file path relative to data/tax */
function readAll() {
  const out = [];
  (function walk(dir) {
    fs.readdirSync(dir, { withFileTypes: true }).forEach((d) => {
      const full = path.join(dir, d.name);
      if (d.isDirectory()) walk(full);
      else if (d.name.endsWith(".json") && full !== path.join(DATA, "index.json")) {
        const rel = path.relative(DATA, full).split(path.sep).join("/");
        let doc;
        try {
          doc = JSON.parse(fs.readFileSync(full, "utf8"));
        } catch (e) {
          throw new Error(rel + ": " + e.message);
        }
        out.push({ file: rel, doc: doc });
      }
    });
  })(DATA);
  return out.sort((a, b) => a.file.localeCompare(b.file));
}

/* The file in force for each id: the latest tax year that has started.
   A year that has not started yet can sit alongside as a draft. */
function currentFiles(all, today) {
  const now = today || new Date().toISOString().slice(0, 10);
  const best = {};
  all.forEach(({ file, doc }) => {
    if (doc.draft || doc.taxYear.start > now) return;
    if (!best[doc.id] || best[doc.id].doc.taxYear.start < doc.taxYear.start) best[doc.id] = { file, doc };
  });
  return best;
}

function buildIndex(all, today) {
  const cur = currentFiles(all, today);
  const jurisdictions = {};
  Object.keys(cur).sort().forEach((id) => {
    const { file, doc } = cur[id];
    jurisdictions[id] = {
      file: file,
      name: doc.name,
      kind: doc.kind,
      country: doc.country,
      parent: doc.parent,
      standalone: !!doc.standalone,
      taxYear: doc.taxYear.label,
      lastVerified: doc.lastVerified
    };
  });
  return {
    _note: "Generated by tools/tax/check.js --write. Do not edit by hand: it maps each jurisdiction id to the data file currently in force.",
    jurisdictions: jurisdictions
  };
}

/* The parent→child chain for a document. A parent is taken from the same
   tax year where one exists, otherwise the parent currently in force. */
function chainFor(doc, all, today) {
  const cur = currentFiles(all, today);
  const chain = [doc];
  let d = doc;
  while (d.parent) {
    const same = all.find((x) => x.doc.id === d.parent && x.doc.taxYear.label === d.taxYear.label);
    const p = same || cur[d.parent];
    if (!p) throw new Error(doc.id + ": parent '" + d.parent + "' not found");
    d = p.doc;
    chain.unshift(d);
  }
  return chain;
}

function loadChain(id, today) {
  const all = readAll();
  const cur = currentFiles(all, today);
  if (!cur[id]) throw new Error("no jurisdiction '" + id + "'");
  return chainFor(cur[id].doc, all, today);
}

module.exports = { ROOT, DATA, readAll, currentFiles, buildIndex, chainFor, loadChain, slugYear };
