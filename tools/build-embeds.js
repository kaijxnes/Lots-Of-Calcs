#!/usr/bin/env node
/* Heights are the embed's measured height at 720px wide plus 20px, so they show without scrolling.

   Embeddable versions of the most-shared calculators, and the "Embed this
   calculator" box on each one's page.

       node tools/build-embeds.js

   /embed/<name>/ is the calculator alone — the page's first <main class="tool">
   and its scripts — with a link back, no cookie banner or tracking, and
   noindex. _headers lets other sites frame /embed/* (everything else stays
   SAMEORIGIN). Built from the finished pages, so run it after the other
   generators; the monthly rebuild does. */
const fs = require("fs");
const path = require("path");
const site = require("./lib/site.js");
const { SITE, esc } = site;

const EMBEDS = [
  ["salary", "/salary/", "Salary after tax calculator", 1420],
  ["vat", "/vat/", "VAT calculator", 600],
  ["percent", "/percent/", "Percentage calculator", 460],
  ["mortgage", "/mortgage-calculator/", "Mortgage calculator", 2000],
  ["loan", "/loan-repayment/", "Loan repayment calculator", 1220],
  ["compound-interest", "/compound-interest/", "Compound interest calculator", 1440],
  ["savings-goal", "/savings-goal/", "Savings goal calculator", 1210],
  ["budget", "/50-30-20-budget/", "50/30/20 budget calculator", 860],
  ["inflation", "/inflation/", "Inflation calculator", 640],
  ["odds", "/odds-converter/", "Odds converter", 910],
  ["each-way", "/each-way/", "Each-way bet calculator", 870],
  ["accumulator", "/accumulator/", "Accumulator calculator", 920],
  ["tip", "/tip/", "Tip calculator", 690],
  ["discount", "/discount/", "Discount calculator", 590],
  ["bmi", "/bmi/", "BMI calculator", 600],
  ["carers-allowance", "/carers-allowance-calculator/", "Carer's Allowance earnings calculator", 850],
  ["winter-fuel-payment", "/winter-fuel-payment-calculator/", "Winter Fuel Payment calculator", 620],
  ["child-maintenance", "/child-maintenance-calculator/", "Child maintenance calculator", 970],
  ["maintenance-loan", "/student-maintenance-loan-calculator/", "Student Maintenance Loan calculator", 720],
  ["state-pension-forecast", "/state-pension-forecast-calculator/", "State Pension forecast calculator", 730],
  ["payslip-checker", "/payslip-checker/", "Payslip checker", 1210]
];

const START = "    <!-- embed box: generated by tools/build-embeds.js -->\n", END = "    <!-- end embed box -->\n";

function read(rel) { return fs.readFileSync(path.join(site.ROOT, rel.replace(/^\//, ""), "index.html"), "utf8"); }

/* the calculator: the page's first part, a <section class="tool"> once
   tools/lib/landmarks.js has run (a <main> on older pages); in the embed it
   is the page's one <main> */
function firstTool(html) {
  const m = html.match(/<(main|section) class="tool(?: [^"]*)?"/);
  if (!m) return null;
  const a = m.index, close = "</" + m[1] + ">", b = html.indexOf(close, a);
  return "<main" + html.slice(a + 1 + m[1].length, b) + "</main>";
}

function scripts(html) {
  const body = html.slice(html.indexOf("<body"));
  return (body.match(/<script\b[^>]*>[\s\S]*?<\/script>/g) || [])
    .filter((t) => !/application\/ld\+json|consent\.js|visits\.js|share\.js/.test(t));
}

function snippet(name, src, title, height) {
  return `<iframe src="${SITE}/embed/${name}/" title="${title} — Lots Of Calcs" width="100%" height="${height}" style="border:0;max-width:720px;" loading="lazy"></iframe>\n<p><a href="${SITE}${src}">${title}</a> by Lots Of Calcs</p>`;
}

function embedPage(name, src, title) {
  const html = read(src), tool = firstTool(html);
  if (!tool) throw new Error("no calculator on " + src);
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${esc(title)} — Lots Of Calcs</title>
<meta name="robots" content="noindex">
<link rel="canonical" href="${SITE}${src}">
<link rel="stylesheet" href="/styles.css">
<base target="_blank">
</head>
<body class="embed-body">
  <div class="page embed-page">
    <p class="embed-head"><a href="${src}">${esc(title)}</a></p>
${tool}
    <p class="embed-foot">Free from <a href="${SITE}${src}">Lots Of Calcs</a> — all calculations run in your browser.</p>
  </div>
${scripts(html).map((s) => "  " + s).join("\n")}
</body>
</html>
`;
}

function box(name, src, title, height) {
  return `    <details class="embed-box">
      <summary>Embed this calculator on your website</summary>
      <p class="tool-hint">Free to use. Paste this into your page's HTML; please keep the link underneath.</p>
      <textarea readonly rows="4" aria-label="Embed code" onclick="this.select()">${esc(snippet(name, src, title, height))}</textarea>
    </details>

`;
}

function addBox(src, html) {
  const file = path.join(site.ROOT, src.replace(/^\//, ""), "index.html");
  let s = fs.readFileSync(file, "utf8");
  /* take out the old box and the blank line written after it, and any blank
     lines earlier runs piled up, so re-running changes nothing */
  if (s.includes(START)) s = s.slice(0, s.indexOf(START)).replace(/\n{3,}$/, "\n\n") + s.slice(s.indexOf(END) + END.length).replace(/^\n+/, "");
  const at = s.indexOf("    <!-- related calculators: generated by tools/related.js -->");
  if (at < 0) throw new Error(src + ": related marker not found");
  s = s.slice(0, at) + START + html + END + "\n" + s.slice(at);
  fs.writeFileSync(file, require("./lib/assets.js").version(s));
}

EMBEDS.forEach(([name, src, title, height]) => {
  addBox(src, box(name, src, title, height));
  site.write(`embed/${name}`, embedPage(name, src, title));
});
site.prune("embed", /^[a-z0-9-]+$/);
console.log(`built ${EMBEDS.length} embeds`);
