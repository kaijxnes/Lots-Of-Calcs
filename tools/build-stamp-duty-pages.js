#!/usr/bin/env node
/* Stamp duty calculator and a page per price:

       /stamp-duty-calculator/           calculator (England & NI, Scotland, Wales)
       /stamp-duty-calculator/300000/    stamp duty on £300,000, every buyer type

       node tools/build-stamp-duty-pages.js

   Rates come from data/property/uk-stamp-duty.json, through stamp-duty.js
   (the calculator's own code). The monthly check confirms the rates and
   re-runs this. */
const fs = require("fs");
const path = require("path");
const site = require("./lib/site.js");
const related = require("./related.js");
const S = require("../stamp-duty.js");
const links = require("./page-links.js");
const { esc, SITE } = site;

const R = JSON.parse(fs.readFileSync(path.join(site.ROOT, "data/property/uk-stamp-duty.json"), "utf8"));
const BASE = "/stamp-duty-calculator/";
const PRICES = [100000, 125000, 150000, 175000, 200000, 225000, 250000, 275000, 300000, 325000, 350000, 375000, 400000, 425000, 450000, 475000, 500000, 550000, 600000, 650000, 700000, 750000, 800000, 900000, 1000000, 1250000, 1500000, 2000000];
const p0 = S.pounds;
const t = (region, price, buyer, nr) => S.calc(R, region, price, buyer, nr);
const E = R.england, SC = R.scotland, W = R.wales;
const sourcesHtml = ["england", "scotland", "wales"].map((k) => R[k].sources.map((s) => `<a href="${s.url}" rel="noopener">${esc(s.title)}</a>`).join(", ")).join("; ");

/* the rates as one JS file the calculator pages share */
fs.writeFileSync(path.join(site.ROOT, "stamp-duty-rates.js"), `/* Residential stamp duty rates for the UK nations, from data/property/uk-stamp-duty.json.
   Generated by tools/build-stamp-duty-pages.js — don't edit by hand. */
var UK_STAMP_DUTY = ${JSON.stringify({ england: E, scotland: SC, wales: W })};
`);

const bandLabel = (r) => (r.ads ? `Additional Dwelling Supplement (${r.rate}% of the price)` : `${r.to ? `${p0(r.from)}–${p0(r.to)}` : `Over ${p0(r.from)}`} at ${r.rate}%`);
const bandRows = (res) => res.rows.map((r) => `<tr><td>${esc(bandLabel(r))}</td><td>${p0(r.part)}</td><td>${p0(r.tax)}</td></tr>`).join("\n");

function tool(price) {
  const r = t("england", price, "home");
  return `    <main class="tool" id="sd-tool">
      <div class="field-row">
        <div class="field"><label for="sd-price">Property price (£)</label><input type="number" id="sd-price" value="${price}" min="0" step="any" inputmode="decimal"></div>
        <div class="field"><label for="sd-region">Where</label><select id="sd-region"><option value="england" selected>England or Northern Ireland</option><option value="scotland">Scotland</option><option value="wales">Wales</option></select></div>
      </div>
      <div class="field-row">
        <div class="field"><label for="sd-buyer">Buying as</label><select id="sd-buyer"><option value="home" selected>Moving home (your only property)</option><option value="ftb">First-time buyer</option><option value="additional">Additional property / second home</option></select></div>
      </div>
      <div class="field" id="sd-nr-row"><label style="display:flex; gap:8px; align-items:center;"><input type="checkbox" id="sd-nr"> Non-UK resident (2% surcharge)</label></div>
      <p class="tool-hint" id="sd-error" role="alert" style="color: var(--bad); display: none;"></p>
      <div class="result-box" aria-live="polite">
        <div class="result-hero">
          <div class="value" id="sd-total">${p0(r.total)}</div>
          <div class="label" id="sd-label">${esc(E.tax)} (${E.short})</div>
        </div>
        <hr class="divider">
        <div class="result-grid">
          <div class="result-row"><span class="r-label">Effective rate</span><span class="r-value" id="sd-eff">${(Math.round(r.effective * 100) / 100).toLocaleString("en-GB")}% of the price</span></div>
        </div>
        <p class="tool-hint" id="sd-note" style="display:none; margin-top:8px;"></p>
      </div>
${site.table(["Band", "Amount in band", "Tax"], []).replace("<tbody>\n\n", `<tbody id="sd-bands">\n${bandRows(r)}\n`)}      <p class="tool-hint" style="margin-top:12px;">Residential purchases; each rate applies only to the part of the price in that band. Rates last checked ${esc(site.niceDate ? site.niceDate(R.lastChecked) : R.lastChecked)} against ${sourcesHtml}.</p>
    </main>
`;
}

function page(price) {
  const url = SITE + `${BASE}${price}/`;
  const h = t("england", price, "home"), f = t("england", price, "ftb"), a = t("england", price, "additional"), n = t("england", price, "home", true);
  const sh = t("scotland", price, "home"), sf = t("scotland", price, "ftb"), sa = t("scotland", price, "additional");
  const wh = t("wales", price, "home"), wa = t("wales", price, "additional");
  const ftbOk = price <= E.firstTimeBuyer.maxPrice;
  const title = `Stamp Duty on ${p0(price)} — ${p0(h.total)}${ftbOk ? `, ${f.total ? p0(f.total) : "£0"} for First-Time Buyers` : ""}`;
  const desc = `Stamp duty on a ${p0(price)} home in England is ${p0(h.total)}${ftbOk ? `, or ${p0(f.total)} for first-time buyers` : " (first-time buyer relief stops at £500,000)"}; ${p0(a.total)} on a second home. In Scotland LBTT is ${p0(sh.total)}, in Wales LTT ${p0(wh.total)}.`;
  const rows = [
    ["Moving home", p0(h.total), p0(sh.total), p0(wh.total)],
    ["First-time buyer", ftbOk ? p0(f.total) : `${p0(f.total)} (no relief over £500,000)`, p0(sf.total), `${p0(wh.total)} (no relief)`],
    ["Additional property", p0(a.total), p0(sa.total), p0(wa.total)],
    ["Non-UK resident", p0(n.total), "—", "—"]
  ];
  const q = [
    [`How much is stamp duty on ${p0(price)}?`, `${p0(h.total)} in England and Northern Ireland if you're moving home: ${h.rows.filter((r) => r.tax > 0).map((r) => `${r.rate}% on ${p0(r.part)}`).join(", ") || "nothing is due at this price"}. That's ${(Math.round(h.effective * 100) / 100).toLocaleString("en-GB")}% of the price.`],
    [`How much stamp duty does a first-time buyer pay on ${p0(price)}?`, ftbOk ? `${p0(f.total)} in England and Northern Ireland: no tax up to £300,000 and 5% on the part from £300,001 to £500,000. That saves ${p0(h.total - f.total)}. In Scotland first-time buyers pay ${p0(sf.total)}; Wales has no first-time buyer relief.` : `${p0(f.total)} — the same as anyone moving home, because first-time buyer relief can't be claimed on homes over £500,000 in England and Northern Ireland.`],
    [`What about a second home or buy-to-let at ${p0(price)}?`, `${p0(a.total)} in England and Northern Ireland, with 5% added to every band. In Scotland the Additional Dwelling Supplement of 8% of the price makes it ${p0(sa.total)}; Wales's higher rates make it ${p0(wa.total)}.`],
    ["When do I pay it?", "In England and Northern Ireland the return and payment are due within 14 days of completion; your solicitor or conveyancer normally files it and pays it for you, out of the money you send them. Scotland and Wales use their own taxes with their own returns, also usually handled by the solicitor."]
  ];
  const ld = [site.webPage(title, desc, url, R.lastChecked), site.breadcrumb([["Home", SITE + "/"], ["Stamp Duty Calculator", SITE + BASE], [`${p0(price)}`, url]]), site.faqLd(q)];
  const near = site.neighbours(PRICES, price, 6).filter((x) => x !== price).map((x) => `<a href="${BASE}${x}/">Stamp duty on ${p0(x)}</a>`).join(" ");
  return site.head({ title, desc, url, ld }) + `    <header class="site-header">
      <a class="back-link" href="${BASE}">← Stamp duty calculator</a>
      <h1 class="page-title">Stamp duty on ${p0(price)}</h1>
      <p class="page-subtitle">${p0(h.total)} if you're moving home in England or Northern Ireland${ftbOk ? `; ${p0(f.total)} for a first-time buyer` : ""}.</p>
    </header>

${tool(price)}
    <main class="tool">
      <h2 class="tool-section-title">${p0(price)} for every buyer, in every nation</h2>
${site.table(["", "England &amp; NI (SDLT)", "Scotland (LBTT)", "Wales (LTT)"], rows, 560)}      <p class="tool-hint" style="margin-top:12px;">Scotland and Wales set their own taxes in place of stamp duty. The non-UK resident surcharge applies in England and Northern Ireland only.</p>
    </main>

    <main class="tool">
      <h2 class="tool-section-title">Frequently asked questions</h2>
${site.faqHtml(q)}    </main>

${(() => {
    const mt = links.mortgageUkNear(price * 0.9), b = links.borrowUkNear(price * 0.9 / 4.5);
    const items = [mt ? `<a href="${mt.url}">Payments on a ${p0(mt.value)} mortgage</a>` : "", b ? `<a href="${b.url}">How much can I borrow on ${p0(b.value)}?</a>` : ""].filter(Boolean);
    return items.length ? `    <main class="tool">
      <h2 class="tool-section-title">Buying at ${p0(price)}</h2>
      <p class="about-text">With a 10% deposit you'd borrow about ${p0(price * 0.9)}, which most lenders would want an income of around ${p0(price * 0.9 / 4.5)} or more for (4.5 times income).</p>
      <p class="salary-links">${items.join(" ")}</p>
    </main>

` : "";
  })()}    <div class="hub-group-title" style="margin-top:28px;">Other prices</div>
    <p class="salary-links">${near}</p>

${site.FOOTER}
  </div>
  <script src="/stamp-duty-rates.js"></script>
  <script src="/stamp-duty.js"></script>
</body>
</html>
`;
}

function hub() {
  const url = SITE + BASE;
  const title = "Stamp Duty Calculator — SDLT, LBTT and LTT for Every UK Nation";
  const desc = `Work out stamp duty on a home in England and Northern Ireland, Land and Buildings Transaction Tax in Scotland or Land Transaction Tax in Wales — for movers, first-time buyers and second homes. ${p0(300000)} costs ${p0(t("england", 300000, "home").total)} in England.`;
  const bandTable = (bands, extra) => bands.map((b, i) => [i + 1 < bands.length ? `${p0(b[0])}–${p0(bands[i + 1][0])}` : `Over ${p0(b[0])}`, `${b[1] + (extra || 0)}%`]);
  const grid = PRICES.map((p) => [`<a href="${BASE}${p}/">${p0(p)}</a>`, p0(t("england", p, "home").total), p0(t("england", p, "ftb").total), p0(t("england", p, "additional").total), p0(t("scotland", p, "home").total), p0(t("wales", p, "home").total)]);
  const q = [
    ["How is stamp duty worked out?", "Like income tax: each rate applies only to the part of the price within its band. On £295,000 in England that's nothing on the first £125,000, 2% on the next £125,000 (£2,500) and 5% on the last £45,000 (£2,250) — £4,750 in all, as GOV.UK's own example shows."],
    ["Do first-time buyers pay stamp duty?", "In England and Northern Ireland, nothing up to £300,000 and 5% from £300,001 to £500,000; above £500,000 the relief doesn't apply at all. In Scotland first-time buyers pay nothing up to £175,000. Wales has no first-time buyer relief."],
    ["How much extra on a second home?", "In England and Northern Ireland, 5% on top of every band (for properties of £40,000 or more). In Scotland, the Additional Dwelling Supplement is 8% of the whole price. Wales has a separate set of higher residential rates, from 5% up to 17%."],
    ["Is there stamp duty in Scotland and Wales?", "Not stamp duty itself: Scotland charges Land and Buildings Transaction Tax (LBTT) and Wales Land Transaction Tax (LTT), each with its own bands, set out below."],
    ["Are these rates current?", `They were last checked on ${R.lastChecked} against GOV.UK, Revenue Scotland and the Welsh Government, and are checked every month.`]
  ];
  const ld = [site.webPage(title, desc, url, R.lastChecked), site.breadcrumb([["Home", SITE + "/"], ["Stamp Duty Calculator", url]]),
    { "@context": "https://schema.org", "@type": "WebApplication", name: "Stamp Duty Calculator", url, applicationCategory: "FinanceApplication", operatingSystem: "Any", offers: { "@type": "Offer", price: "0", priceCurrency: "GBP" } }, site.faqLd(q)];
  return site.head({ title, desc, url, ld }) + `    <header class="site-header">
      <a class="back-link" href="/">← All calculators</a>
      <h1 class="page-title">Stamp duty calculator</h1>
      <p class="page-subtitle">The tax on buying a home in England and Northern Ireland, Scotland or Wales.</p>
    </header>

${tool(300000)}
    <main class="tool">
      <h2 class="tool-section-title">Stamp duty by price</h2>
${site.table(["Price", "England &amp; NI", "First-time buyer", "Second home", "Scotland", "Wales"], grid, 600)}      <p class="tool-hint" style="margin-top:12px;">England and NI columns are SDLT; Scotland is LBTT for someone moving home; Wales is LTT at the main rates. Pick a price for every buyer type in every nation.</p>
    </main>

    <main class="tool">
      <h2 class="tool-section-title">The rates</h2>
      <p class="salary-links-title">England and Northern Ireland (SDLT)</p>
${site.table(["Part of the price", "Rate"], bandTable(E.bands), 300)}      <p class="tool-hint">First-time buyers: 0% to £300,000, 5% to £500,000 (no relief above £500,000). Additional properties: +5% on every band. Non-UK residents: +2%.</p>
      <p class="salary-links-title" style="margin-top:18px;">Scotland (LBTT)</p>
${site.table(["Part of the price", "Rate"], bandTable(SC.bands), 300)}      <p class="tool-hint">First-time buyers: nil band raised to £175,000. Additional properties: Additional Dwelling Supplement of 8% of the price.</p>
      <p class="salary-links-title" style="margin-top:18px;">Wales (LTT)</p>
${site.table(["Part of the price", "Main rate", "Higher rate"], (() => { const cuts = Array.from(new Set(W.bands.map((b) => b[0]).concat(W.higherBands.map((b) => b[0])))).sort((x, y) => x - y); const rateAt = (bands, v) => bands.filter((b) => b[0] <= v).pop()[1]; return cuts.map((c, i) => [i + 1 < cuts.length ? `${p0(c)}–${p0(cuts[i + 1])}` : `Over ${p0(c)}`, `${rateAt(W.bands, c)}%`, `${rateAt(W.higherBands, c)}%`]); })(), 360)}      <p class="tool-hint">Higher rates apply to additional properties. No first-time buyer relief. Sources: ${sourcesHtml}.</p>
    </main>

    <main class="tool">
      <h2 class="tool-section-title">Frequently asked questions</h2>
${site.faqHtml(q)}    </main>

${related.block(BASE)}
${site.FOOTER}
  </div>
  <script src="/stamp-duty-rates.js"></script>
  <script src="/stamp-duty.js"></script>
</body>
</html>
`;
}

/* GOV.UK's worked examples, and hand checks for Scotland and Wales */
[["england", 295000, "home", 4750], ["england", 500000, "ftb", 10000], ["scotland", 300000, "ftb", 4000], ["wales", 300000, "additional", 19950]].forEach(([r, p, b, want]) => {
  const got = t(r, p, b).total;
  if (Math.abs(got - want) > 0.005) throw new Error(`stamp duty check ${r} ${p} ${b}: ${got} != ${want}`);
});

const urls = [];
site.write("stamp-duty-calculator", hub());
PRICES.forEach((p) => { site.write(`stamp-duty-calculator/${p}`, page(p)); urls.push([`${BASE}${p}/`, "0.6"]); });
site.prune("stamp-duty-calculator", /^\d+$/);
site.sitemapBlock("stamp duty pages", "tools/build-stamp-duty-pages.js", urls);
console.log(`built ${urls.length + 1} stamp duty pages (rates checked ${R.lastChecked})`);
